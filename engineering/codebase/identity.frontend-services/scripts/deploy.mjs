// Copies apps/web/dist into the .NET host's wwwroot for a single deployment.
import { rm, mkdir, cp, access, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const distDir = fileURLToPath(new URL('../apps/web/dist/', import.meta.url));
const wwwroot = new URL('../../identity.backend-services/service/Identity.Api/wwwroot/', import.meta.url);

try {
  await access(new URL('../apps/web/dist/index.html', import.meta.url));
} catch {
  console.error(`[deploy] Built app not found at ${distDir}; run "pnpm build" first.`);
  process.exit(1);
}

await rm(wwwroot, { recursive: true, force: true });
await mkdir(wwwroot, { recursive: true });
await cp(distDir, wwwroot, { recursive: true });

// Keep the directory tracked in git after the wipe (the built assets themselves are gitignored).
await writeFile(
  new URL('.gitkeep', wwwroot),
  '# Build output dir — keep tracked; the SPA assets here are gitignored and regenerated by `pnpm run deploy`.\n',
);

console.log(`[deploy] Copied ${distDir} to ${fileURLToPath(wwwroot)}`);
