-- 003-spine — the shared spine of every instance: sessions, the sign-in log and the Data Protection key ring.
--
-- IdentityDbContext maps them column for column; the Migrations test tier compares the two. {{schema}} is
-- Identity:Database:Schema (default identity). PostgreSQL only: the SQLite dialect retired before this migration.
--
-- Rules as in 001: no foreign keys (user_id and session_id are plain keys), instants are timestamptz, lengths are the
-- model's. Personal data stays masked: ip_masked holds the network only, subject_masked a shortened login.

-- ── Sessions ────────────────────────────────────────────────────────────────────────────────────────────────────────

-- One row per signed-in browser or device; its id is the sid claim of the cookie and of every OIDC token issued under
-- it. A session lives while revoked_at is null, expires_at lies ahead and security_stamp equals the person's.
CREATE TABLE {{schema}}.identity_sessions (
    id                     uuid         NOT NULL,
    user_id                uuid         NOT NULL,
    authentication_methods text[]       NOT NULL,
    security_stamp         varchar(64)  NULL,
    created_at             timestamptz  NOT NULL,
    last_seen_at           timestamptz  NOT NULL,
    expires_at             timestamptz  NOT NULL,
    revoked_at             timestamptz  NULL,
    revoke_reason          varchar(32)  NULL,
    ip_masked              varchar(64)  NULL,
    user_agent             varchar(256) NULL,
    CONSTRAINT pk_identity_sessions PRIMARY KEY (id)
);

CREATE INDEX ix_identity_sessions_user_id ON {{schema}}.identity_sessions (user_id);

-- ── Sign-in log ─────────────────────────────────────────────────────────────────────────────────────────────────────

-- Every attempt, written once; a cleanup job deletes rows past the retention window (Identity:SignInLog:RetentionDays).
-- A plain table for now: monthly partitions wait until the volume asks for them.
CREATE TABLE {{schema}}.identity_sign_in_log (
    id             bigint GENERATED BY DEFAULT AS IDENTITY,
    occurred_at    timestamptz  NOT NULL,
    user_id        uuid         NULL,
    subject_masked varchar(100) NULL,
    method         varchar(32)  NOT NULL,
    client_id      varchar(100) NULL,
    result         varchar(32)  NOT NULL,
    reason         varchar(64)  NULL,
    ip_masked      varchar(64)  NULL,
    user_agent     varchar(256) NULL,
    session_id     uuid         NULL,
    trace_id       varchar(32)  NULL,
    CONSTRAINT pk_identity_sign_in_log PRIMARY KEY (id)
);

CREATE INDEX ix_identity_sign_in_log_occurred_at ON {{schema}}.identity_sign_in_log (occurred_at);
CREATE INDEX ix_identity_sign_in_log_user_id ON {{schema}}.identity_sign_in_log (user_id);

-- ── Data Protection ─────────────────────────────────────────────────────────────────────────────────────────────────

-- The instance's ASP.NET Core Data Protection ring, shared by its replicas; outside a local run each key's secret is
-- encrypted to the ring certificate from the settings (Identity:DataProtection:Certificates).
CREATE TABLE {{schema}}.identity_data_protection_keys (
    id            integer GENERATED BY DEFAULT AS IDENTITY,
    friendly_name text    NULL,
    xml           text    NOT NULL,
    CONSTRAINT pk_identity_data_protection_keys PRIMARY KEY (id)
);
