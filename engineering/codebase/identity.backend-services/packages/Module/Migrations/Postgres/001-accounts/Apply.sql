-- 001-accounts — the identity schema's first 11 tables: accounts, roles, claims, logins, stored tokens, refresh tokens,
-- passkeys, organizations and memberships (PostgreSQL).
--
-- The canonical schema: IdentityDbContext maps over it column for column and never generates it; the Migrations test
-- tier compares the two. {{schema}} is Identity:Database:Schema (default identity), which the migrator creates and
-- claims before this runs. Tables keep the identity_ prefix.
--
-- Rules: uuid ids are v7, made in code; claim rows take a bigint identity; instants are timestamptz; lengths are the
-- model's. Every statement is guarded (IF NOT EXISTS), so a rerun succeeds and changes nothing. No foreign keys inside
-- the set: a user's relation rows leave with it in code. Products may key into identity_users and identity_organizations
-- (the set's referenceable tables) inside one database.

-- ── Accounts ────────────────────────────────────────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS {{schema}}.identity_users (
    id                     uuid         NOT NULL,
    user_name              varchar(256) NULL,
    normalized_user_name   varchar(256) NULL,
    email                  varchar(320) NULL,
    normalized_email       varchar(320) NULL,
    email_confirmed        boolean      NOT NULL,
    password_hash          text         NULL,
    security_stamp         text         NULL,
    concurrency_stamp      text         NULL,
    phone_number           varchar(32)  NULL,
    phone_number_confirmed boolean      NOT NULL,
    two_factor_enabled     boolean      NOT NULL,
    lockout_end            timestamptz  NULL,
    lockout_enabled        boolean      NOT NULL,
    access_failed_count    integer      NOT NULL,
    created_at             timestamptz  NOT NULL,
    updated_at             timestamptz  NOT NULL,
    deleted_at             timestamptz  NULL,
    CONSTRAINT pk_identity_users PRIMARY KEY (id)
);

-- Accounts are soft-deleted: deleting one sets deleted_at and keeps the row; erasing one also scrubs its personal
-- columns in place. The row never leaves, so a product's RESTRICT key into identity_users never blocks. IdentityDbContext
-- hides deleted rows from every query and filters both indexes as here. The user-name index is unique among live
-- accounts, so a deleted account frees its name; the email index stays non-unique, since UserOptions.RequireUniqueEmail
-- may be off.
CREATE UNIQUE INDEX IF NOT EXISTS ix_identity_users_normalized_user_name
    ON {{schema}}.identity_users (normalized_user_name) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_identity_users_normalized_email
    ON {{schema}}.identity_users (normalized_email) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_identity_users_phone_number ON {{schema}}.identity_users (phone_number);

CREATE TABLE IF NOT EXISTS {{schema}}.identity_roles (
    id                uuid         NOT NULL,
    name              varchar(256) NULL,
    normalized_name   varchar(256) NULL,
    concurrency_stamp text         NULL,
    created_at        timestamptz  NOT NULL,
    updated_at        timestamptz  NOT NULL,
    CONSTRAINT pk_identity_roles PRIMARY KEY (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS ix_identity_roles_normalized_name ON {{schema}}.identity_roles (normalized_name);

CREATE TABLE IF NOT EXISTS {{schema}}.identity_user_roles (
    user_id uuid NOT NULL,
    role_id uuid NOT NULL,
    CONSTRAINT pk_identity_user_roles PRIMARY KEY (user_id, role_id)
);

CREATE TABLE IF NOT EXISTS {{schema}}.identity_user_claims (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id     uuid   NOT NULL,
    claim_type  text   NULL,
    claim_value text   NULL,
    CONSTRAINT pk_identity_user_claims PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS ix_identity_user_claims_user_id ON {{schema}}.identity_user_claims (user_id);

CREATE TABLE IF NOT EXISTS {{schema}}.identity_role_claims (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    role_id     uuid   NOT NULL,
    claim_type  text   NULL,
    claim_value text   NULL,
    CONSTRAINT pk_identity_role_claims PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS ix_identity_role_claims_role_id ON {{schema}}.identity_role_claims (role_id);

CREATE TABLE IF NOT EXISTS {{schema}}.identity_user_logins (
    login_provider        varchar(128) NOT NULL,
    provider_key          varchar(128) NOT NULL,
    provider_display_name text         NULL,
    user_id               uuid         NOT NULL,
    CONSTRAINT pk_identity_user_logins PRIMARY KEY (login_provider, provider_key)
);

CREATE INDEX IF NOT EXISTS ix_identity_user_logins_user_id ON {{schema}}.identity_user_logins (user_id);

CREATE TABLE IF NOT EXISTS {{schema}}.identity_user_tokens (
    user_id        uuid         NOT NULL,
    login_provider varchar(128) NOT NULL,
    name           varchar(128) NOT NULL,
    value          text         NULL,
    CONSTRAINT pk_identity_user_tokens PRIMARY KEY (user_id, login_provider, name)
);

-- ── Credentials ─────────────────────────────────────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS {{schema}}.identity_refresh_tokens (
    id             uuid        NOT NULL,
    user_id        uuid        NOT NULL,
    family_id      uuid        NOT NULL,
    token_hash     varchar(64) NOT NULL,
    security_stamp varchar(64) NULL,
    created_at     timestamptz NOT NULL,
    expires_at     timestamptz NOT NULL,
    consumed_at    timestamptz NULL,
    revoked_at     timestamptz NULL,
    CONSTRAINT pk_identity_refresh_tokens PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS ix_identity_refresh_tokens_user_id ON {{schema}}.identity_refresh_tokens (user_id);
CREATE INDEX IF NOT EXISTS ix_identity_refresh_tokens_family_id ON {{schema}}.identity_refresh_tokens (family_id);

CREATE TABLE IF NOT EXISTS {{schema}}.identity_passkeys (
    id            uuid         NOT NULL,
    user_id       uuid         NOT NULL,
    credential_id bytea        NOT NULL,
    public_key    bytea        NOT NULL,
    user_handle   bytea        NOT NULL,
    sign_count    bigint       NOT NULL,
    aa_guid       uuid         NOT NULL,
    name          varchar(100) NOT NULL,
    created_at    timestamptz  NOT NULL,
    last_used_at  timestamptz  NULL,
    CONSTRAINT pk_identity_passkeys PRIMARY KEY (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS ix_identity_passkeys_credential_id ON {{schema}}.identity_passkeys (credential_id);
CREATE INDEX IF NOT EXISTS ix_identity_passkeys_user_id ON {{schema}}.identity_passkeys (user_id);

-- ── Organizations ───────────────────────────────────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS {{schema}}.identity_organizations (
    id         uuid         NOT NULL,
    name       varchar(120) NOT NULL,
    slug       varchar(64)  NOT NULL,
    created_at timestamptz  NOT NULL,
    CONSTRAINT pk_identity_organizations PRIMARY KEY (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS ix_identity_organizations_slug ON {{schema}}.identity_organizations (slug);

CREATE TABLE IF NOT EXISTS {{schema}}.identity_memberships (
    organization_id uuid        NOT NULL,
    user_id         uuid        NOT NULL,
    role            varchar(64) NOT NULL,
    created_at      timestamptz NOT NULL,
    CONSTRAINT pk_identity_memberships PRIMARY KEY (organization_id, user_id)
);

CREATE INDEX IF NOT EXISTS ix_identity_memberships_user_id ON {{schema}}.identity_memberships (user_id);
